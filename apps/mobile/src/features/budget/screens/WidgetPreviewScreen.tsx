import { useState } from 'react';
import { createBudgetExample, type BudgetPlan } from '@budget-builder/contracts';
import { Screen } from '../../../foundation/components/Screen';
import { AppText } from '../../../foundation/components/AppText';
import { Button } from '../../../foundation/components/Button';
import { BudgetEditor } from '../components/BudgetEditor';

function samplePlan(): BudgetPlan {
  // Independently authored API example, never account-derived data.
  const plan = JSON.parse(JSON.stringify(createBudgetExample.plan)) as BudgetPlan;
  plan.name = 'Sample monthly budget';
  plan.pots[1]!.rows[2]!.source = {
    kind: 'SUGGESTED',
    explanation:
      'Sample calculation: DKK 2,700 quarterly divided by three gives DKK 900 per month.',
    recordIds: [],
    period: null,
  };
  return plan;
}
export function WidgetPreviewScreen({
  onBack,
  onDirty,
}: {
  onBack: () => void;
  onDirty: () => void;
}) {
  const [initialPlan] = useState(samplePlan);
  return (
    <Screen>
      <Button label="Back" variant="secondary" onPress={onBack} />
      <AppText variant="title" accessibilityRole="header">
        Sample widget editor
      </AppText>
      <AppText>
        Try editing these fictional amounts. They are not based on your account or generated by AI.
        Nothing is saved.
      </AppText>
      <BudgetEditor initialPlan={initialPlan} onDirty={onDirty} />
    </Screen>
  );
}
